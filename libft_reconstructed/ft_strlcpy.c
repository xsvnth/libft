#include "libft.h"

size_t	ft_strlcpy(char *dest, const char *src, size_t dstsize)
{
	size_t	lensrc;

	lensrc = ft_strlen(src);
	if (!dstsize)
		return (lensrc);
	while (--dstsize && *src)
		*dest++ = *src++;
	*dest = '\0';
	return (lensrc);
}
